#!/usr/bin/env node
// Builds every design-token output from the single source of truth:
//   tokens/tokens.json   (W3C Design Tokens format, edit this)
//     → src/styles/tokens.css             CSS custom properties for the app
//     → src/styles/tokens.js              resolved values for JS (Mapbox, canvas, Recharts)
//     → tokens/figma/tokens-studio.json   import into Figma via the Tokens Studio plugin
//
// Zero dependencies on purpose. If the pipeline outgrows this, the same
// tokens.json drops straight into Style Dictionary.
//
//   npm run tokens

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const src = JSON.parse(readFileSync(resolve(root, 'tokens/tokens.json'), 'utf8'))

// ── flatten ────────────────────────────────────────────────────────────────
const flat = new Map() // 'color.white.04' -> { value, type, description }
;(function walk(node, path) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue
    if (v && typeof v === 'object' && '$value' in v) {
      flat.set([...path, k].join('.'), { value: v.$value, type: v.$type, description: v.$description })
    } else if (v && typeof v === 'object') {
      walk(v, [...path, k])
    }
  }
})(src, [])

const isRef = (v) => typeof v === 'string' && /^\{[^}]+\}$/.test(v)
const refPath = (v) => v.slice(1, -1)

function resolveValue(value, seen = []) {
  if (!isRef(value)) return value
  const p = refPath(value)
  if (seen.includes(p)) throw new Error(`Circular token reference: ${[...seen, p].join(' → ')}`)
  const t = flat.get(p)
  if (!t) throw new Error(`Unresolved token reference: ${value}`)
  return resolveValue(t.value, [...seen, p])
}

const cssVar = (path) => '--' + path.replaceAll('.', '-')

function cssValue(tok) {
  const { value, type } = tok
  if (isRef(value)) return `var(${cssVar(refPath(value))})`
  if (type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`
  return String(value)
}

// ── tokens.css ─────────────────────────────────────────────────────────────
const groups = new Map()
for (const [path, tok] of flat) {
  const g = path.split('.').slice(0, path.startsWith('color.') ? 2 : 1).join('.')
  if (!groups.has(g)) groups.set(g, [])
  groups.get(g).push([path, tok])
}
let css = '/* AUTO-GENERATED by scripts/build-tokens.mjs from tokens/tokens.json — do not edit. */\n:root {\n'
for (const [g, items] of groups) {
  css += `\n  /* ${g} */\n`
  items.sort(([a], [b]) => a.localeCompare(b, 'en', { numeric: true }))
  for (const [path, tok] of items) {
    css += `  ${cssVar(path)}: ${cssValue(tok)};\n`
  }
}
css += '}\n'
mkdirSync(resolve(root, 'src/styles'), { recursive: true })
writeFileSync(resolve(root, 'src/styles/tokens.css'), css)

// ── tokens.js (resolved) ───────────────────────────────────────────────────
const nested = {}
for (const [path, tok] of flat) {
  let v = resolveValue(tok.value)
  if (tok.type === 'cubicBezier') v = `cubic-bezier(${v.join(', ')})`
  const parts = path.split('.')
  let o = nested
  for (const p of parts.slice(0, -1)) o = o[p] ??= {}
  o[parts.at(-1)] = v
}
writeFileSync(
  resolve(root, 'src/styles/tokens.js'),
  '// AUTO-GENERATED by scripts/build-tokens.mjs from tokens/tokens.json — do not edit.\n' +
  '// Resolved values for places CSS variables cannot reach (Mapbox paint, canvas, Recharts).\n' +
  `export const tokens = ${JSON.stringify(nested, null, 2)}\n`
)

// ── Tokens Studio (Figma) ──────────────────────────────────────────────────
const TS_TYPE = (path, type) => {
  if (path.startsWith('font.size')) return 'fontSizes'
  if (path.startsWith('font.family')) return 'fontFamilies'
  if (path.startsWith('font.weight')) return 'fontWeights'
  if (path.startsWith('font.line-height')) return 'lineHeights'
  if (path.startsWith('font.tracking')) return 'letterSpacing'
  if (path.startsWith('radius')) return 'borderRadius'
  if (path.startsWith('space')) return 'spacing'
  if (path.startsWith('size')) return 'sizing'
  if (path.startsWith('breakpoint')) return 'sizing'
  if (path.startsWith('shadow')) return 'boxShadow'
  if (type === 'color') return 'color'
  return 'other'
}
function parseShadow(str) {
  // "0 4px 20px rgba(0, 0, 0, 0.45)" → Tokens Studio boxShadow object
  const m = str.match(/^(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(\d+)(?:px)?\s+(?:(-?\d+)(?:px)?\s+)?(rgba?\(.+\)|#[0-9a-f]+)$/i)
  if (!m) throw new Error(`Cannot parse shadow: ${str}`)
  return { x: m[1], y: m[2], blur: m[3], spread: m[4] ?? '0', color: m[5], type: 'dropShadow' }
}
const isSemantic = (p) => /^color\.(text|surface|border|accent|status|boundary|highlight|info|country)\./.test(p)
const sets = { primitives: {}, semantic: {} }
for (const [path, tok] of flat) {
  const set = isSemantic(path) ? sets.semantic : sets.primitives
  const type = TS_TYPE(path, tok.type)
  let value = tok.value
  if (type === 'boxShadow') value = parseShadow(value)
  else if (tok.type === 'cubicBezier') value = `cubic-bezier(${value.join(', ')})`
  else if (!isRef(value)) value = String(value)
  const parts = path.split('.')
  let o = set
  for (const p of parts.slice(0, -1)) o = o[p] ??= {}
  o[parts.at(-1)] = { value, type, ...(tok.description ? { description: tok.description } : {}) }
}
const studio = {
  ...sets,
  $themes: [],
  $metadata: { tokenSetOrder: ['primitives', 'semantic'] },
}
mkdirSync(resolve(root, 'tokens/figma'), { recursive: true })
writeFileSync(resolve(root, 'tokens/figma/tokens-studio.json'), JSON.stringify(studio, null, 2) + '\n')

console.log(`tokens: ${flat.size} → src/styles/tokens.css, src/styles/tokens.js, tokens/figma/tokens-studio.json`)
